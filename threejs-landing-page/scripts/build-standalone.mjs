/**
 * Generates a single self-contained `standalone.html` from the Vite sources so
 * the site can be hosted from a raw file URL (e.g. raw.githack.com) without a
 * build step. It inlines the CSS, inlines app.js as a module, and adds an
 * import map that loads Three.js + GSAP from a CDN.
 *
 *   node scripts/build-standalone.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

const css = read('src/css/style.css');
const js = read('src/js/app.js');
let html = read('index.html');

const ADDONS = [
  'postprocessing/EffectComposer.js',
  'postprocessing/RenderPass.js',
  'postprocessing/UnrealBloomPass.js',
  'postprocessing/ShaderPass.js',
  'postprocessing/OutputPass.js',
  'math/SimplexNoise.js',
];
const addonEntries = ADDONS.map(
  (p) =>
    `          "three/addons/${p}": "https://esm.sh/three@0.169.0/examples/jsm/${p}?external=three"`
).join(',\n');

const importmap = `<script type="importmap">
      {
        "imports": {
          "three": "https://esm.sh/three@0.169.0",
          "three/addons/": "https://esm.sh/three@0.169.0/examples/jsm/",
${addonEntries},
          "gsap": "https://esm.sh/gsap@3.12.5"
        }
      }
    </script>`;

// 1. Inline the stylesheet.
html = html.replace(
  '<link rel="stylesheet" href="/src/css/style.css" />',
  `<style>\n${css}\n    </style>`
);

// 2. Add the import map just before </head>.
html = html.replace('</head>', `    ${importmap}\n  </head>`);

// 3. Inline the module script.
html = html.replace(
  '<script type="module" src="/src/js/app.js"></script>',
  `<script type="module">\n${js}\n    </script>`
);

const banner = '<!-- AUTO-GENERATED by scripts/build-standalone.mjs — edit src/ instead -->\n';
writeFileSync(resolve(root, 'standalone.html'), banner + html);
console.log('✓ standalone.html generated');
