function setDotted(obj, dotted, value) {
  const parts = dotted.split('.');
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (typeof cur[parts[i]] !== 'object' || cur[parts[i]] === null) cur[parts[i]] = {};
    cur = cur[parts[i]];
  }
  cur[parts[parts.length - 1]] = value;
}

let langCount = 0;
let cellCount = 0;
for (const [lang, values] of Object.entries(T)) {
  const file = path.join(LOCALES, lang, 'translation.json');
  if (!fs.existsSync(file)) { console.error(`✗ missing locale: ${lang}`); continue; }
  if (values.length !== KEYS.length) {
    console.error(`✗ ${lang}: ${values.length} values, expected ${KEYS.length} — übersprungen`);
    continue;
  }
  const obj = JSON.parse(fs.readFileSync(file, 'utf8'));
  KEYS.forEach((k, i) => { setDotted(obj, k, values[i]); cellCount++; });
  fs.writeFileSync(file, JSON.stringify(obj, null, 2) + '\n', 'utf8');
  langCount++;
}
